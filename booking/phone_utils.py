"""Нормализация и форматирование российских номеров телефонов.

Нормализованный формат (для хранения):  +79161234567  (12 символов)
Формат для отображения:                 +7 (916) 123-45-67
"""
import re


def normalize_phone(raw):
    """Привести номер к единому формату +7XXXXXXXXXX.

    Поддерживает:
      +7 (916) 123-45-67
      8 (916) 123-45-67
      89161234567
      +79161234567
      79161234567
      +7-916-123-45-67
      и любые вариации

    Возвращает '' если raw пустой или номер не удалось распарсить.
    Иначе +7XXXXXXXXXX.
    """
    if not raw:
        return ''

    digits = re.sub(r'\D', '', raw)

    # 10 цифр — без кода страны, добавляем 7
    if len(digits) == 10:
        return '+' + '7' + digits

    # 11 цифр — с кодом страны
    if len(digits) == 11:
        if digits.startswith('8'):
            return '+' + '7' + digits[1:]
        if digits.startswith('7'):
            return '+' + digits

    # Не удалось распарсить
    return ''


def format_phone(raw):
    """Привести номер к формату для отображения: +7 (916) 123-45-67.

    Принимает любой формат (сначала нормализует).
    Возвращает '' если raw пустой, иначе отформатированный номер.
    """
    n = normalize_phone(raw)
    if not n:
        return ''

    # Ожидаем +7XXXXXXXXXX (12 символов)
    if len(n) == 12 and n.startswith('+7'):
        return f'+7 ({n[2:5]}) {n[5:8]}-{n[8:10]}-{n[10:12]}'

    # Если нормализация не удалась — возвращаем исходник
    return raw
